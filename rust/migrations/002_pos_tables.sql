-- 收银桌台区
-- area_id 区域ID，shop_id 店铺ID，area_name 区域名称，sort 排序
CREATE TABLE IF NOT EXISTS pos_table_area (
    area_id   INT GENERATED BY DEFAULT AS IDENTITY,
    shop_id   INT         NOT NULL DEFAULT 0,
    area_name VARCHAR(64) NOT NULL DEFAULT '',
    sort      INT         NOT NULL DEFAULT 0,
    add_time  INT,
    PRIMARY KEY (area_id)
);
CREATE INDEX IF NOT EXISTS idx_pos_table_area_idx_shop ON pos_table_area (shop_id);

-- 收银桌台
-- table_id 桌台ID，shop_id 店铺ID，area_id 区域ID，
-- table_name 桌台名称，capacity 容纳人数，
-- status 语义：0 空闲 1 占用，order_id 当前订单ID，
-- user_id 当前绑定会员，remark 备注
CREATE TABLE IF NOT EXISTS pos_table (
    table_id    INT          GENERATED BY DEFAULT AS IDENTITY,
    shop_id     INT          NOT NULL DEFAULT 0,
    area_id     INT          NOT NULL DEFAULT 0,
    table_name  VARCHAR(64)  NOT NULL DEFAULT '',
    capacity    INT          NOT NULL DEFAULT 4,
    status      INT          NOT NULL DEFAULT 0,
    order_id    INT          NOT NULL DEFAULT 0,
    user_id     INT          NOT NULL DEFAULT 0,
    remark      VARCHAR(255) DEFAULT '',
    add_time    INT,
    update_time INT,
    PRIMARY KEY (table_id)
);
CREATE INDEX IF NOT EXISTS idx_pos_table_idx_shop_area ON pos_table (shop_id, area_id);

-- 挂单类别与桌台关联（pos_pending_order 复用列）
-- kind 语义：0 工作中购物车草稿 1 已保存挂单，table_id 关联桌台
ALTER TABLE IF EXISTS pos_pending_order ADD COLUMN IF NOT EXISTS kind INT NOT NULL DEFAULT 0;
ALTER TABLE IF EXISTS pos_pending_order ADD COLUMN IF NOT EXISTS table_id INT NOT NULL DEFAULT 0;

-- 挂单/购物车明细
-- pending_id 挂单ID，price 单价（含改价），
-- origin_price 原价，sku_data 规格 JSON
CREATE TABLE IF NOT EXISTS pos_pending_order_item (
    item_id      BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    pending_id   INT            NOT NULL,
    product_id   BIGINT         NOT NULL DEFAULT 0,
    sku_id       BIGINT         NOT NULL DEFAULT 0,
    product_name VARCHAR(768)   DEFAULT '',
    pic_thumb    VARCHAR(500)   DEFAULT '',
    price        NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    origin_price NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    quantity     INT            NOT NULL DEFAULT 1,
    is_checked   INT            NOT NULL DEFAULT 1,
    sku_data     TEXT,
    add_time     INT,
    PRIMARY KEY (item_id)
);
CREATE INDEX IF NOT EXISTS idx_pos_pending_order_it_idx_pending ON pos_pending_order_item (pending_id);
