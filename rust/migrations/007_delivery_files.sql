-- ============================================================
-- 007_delivery_files.sql
-- 虚拟/付费商品文件型交付（我方新增，原版无附件交付通道）。
-- 商家为 type=2 虚拟商品 / type=4 付费内容商品挂附件，买家购买后
-- 申领短时效令牌下载：附件元数据表 + 交付令牌表（绑订单+用户+文件，
-- 30 分钟有效、单令牌最多 5 次下载，常量见 core 模型 product_delivery）。
-- 时间戳为秒级 INT（与既有表一致），文件大小为 BIGINT。
-- 附件删除采用软删 is_del，保留审计痕迹。
-- 注意：迁移执行器按分号逐条执行且会剥离 -- 注释行，语句内勿写分号。
-- ============================================================

CREATE TABLE IF NOT EXISTS product_delivery_file (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INT NOT NULL,
    shop_id INT NOT NULL DEFAULT 0,
    file_name VARCHAR(300) NOT NULL DEFAULT '',
    file_key VARCHAR(500) NOT NULL DEFAULT '',
    file_ext VARCHAR(16) NOT NULL DEFAULT '',
    file_size BIGINT NOT NULL DEFAULT 0,
    sort INT NOT NULL DEFAULT 0,
    is_del INT NOT NULL DEFAULT 0,
    add_time INT NOT NULL DEFAULT 0,
    update_time INT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_delivery_file_product ON product_delivery_file (product_id, is_del, sort, id);

CREATE TABLE IF NOT EXISTS product_delivery_token (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(64) NOT NULL,
    order_id INT NOT NULL,
    user_id INT NOT NULL,
    file_id INT NOT NULL,
    product_id INT NOT NULL DEFAULT 0,
    max_downloads INT NOT NULL DEFAULT 5,
    download_count INT NOT NULL DEFAULT 0,
    expires_at INT NOT NULL DEFAULT 0,
    add_time INT NOT NULL DEFAULT 0,
    last_download_time INT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_delivery_token_token ON product_delivery_token (token);

CREATE INDEX IF NOT EXISTS idx_delivery_token_order_file ON product_delivery_token (order_id, file_id);
