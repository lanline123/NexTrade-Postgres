-- 028_proxy_hall.sql
-- 代客下单接单大厅（二期，论坛帖 547750 余项，我方新增）：
-- 一期为下单时按地址就近选定履约门店（直选模式）；二期新增
-- 「接单大厅」模式——代客单提交后先进待接单池，同体系营业
-- 门店抢单或由下单店/平台派单，接单后履约店落 proxy_order_ext
-- 的 fulfill_shop_id，结算三方分成沿一期口径不变。
-- 本迁移只在 proxy_order_ext 上增量加接单状态机列，并新增
-- 拒单记录表；一期直选单 hall_status 恒 0、行为逐字不变。
-- 口径：hall_status 0 非大厅单 / 1 待接单 / 2 已接单 /
--   3 履约店已备货 / 4 已关闭（订单取消联动关闭）；
--   assign_type 0 无 / 1 抢单 / 2 派单 / 3 超时兜底改派下单店。
--   超时无人接单时按订单设置 proxyHallFallback 处置（默认 1 =
--   自动改派下单店自履约，fulfill 落下单店、结算退化同店口径）。
-- 部署顺序：本迁移必须先于新二进制换版执行（新版会读写新列
--   与新表，旧版对新列/新表不敏感，反序安全、正序必需）。
-- 注意：迁移执行器按分号逐条执行且会剥离 -- 注释行，语句内勿写分号。
-- ============================================================

ALTER TABLE proxy_order_ext ADD COLUMN IF NOT EXISTS hall_status INT NOT NULL DEFAULT 0;

ALTER TABLE proxy_order_ext ADD COLUMN IF NOT EXISTS hall_deadline INT NOT NULL DEFAULT 0;

ALTER TABLE proxy_order_ext ADD COLUMN IF NOT EXISTS accept_time INT;

ALTER TABLE proxy_order_ext ADD COLUMN IF NOT EXISTS accept_admin_id INT NOT NULL DEFAULT 0;

ALTER TABLE proxy_order_ext ADD COLUMN IF NOT EXISTS assign_type INT NOT NULL DEFAULT 0;

ALTER TABLE proxy_order_ext ADD COLUMN IF NOT EXISTS reassign_count INT NOT NULL DEFAULT 0;

ALTER TABLE proxy_order_ext ADD COLUMN IF NOT EXISTS ready_time INT;

CREATE INDEX IF NOT EXISTS idx_proxy_order_ext_hall ON proxy_order_ext (hall_status, hall_deadline);

CREATE TABLE IF NOT EXISTS proxy_hall_reject (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL DEFAULT 0,
    shop_id integer NOT NULL DEFAULT 0,
    admin_id integer NOT NULL DEFAULT 0,
    reason varchar(255) NOT NULL DEFAULT '',
    add_time integer NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_proxy_hall_reject_order ON proxy_hall_reject (order_id, shop_id);
