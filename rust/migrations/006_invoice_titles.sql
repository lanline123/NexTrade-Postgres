-- 常用发票抬头管理（Tigshop v5.8.65 功能二，原版有，我方自研实现）。
-- 用户自助抬头簿：多条 + 默认唯一 + 申请时自动填充，与既有单条专票
-- 资质表 user_invoice（带审核流）并行存在、互不迁移。
-- 时间戳为秒级 INT（与 order_invoice / user_invoice 等既有表一致）。
-- 删除采用软删 is_del（用户自助数据，保留审计痕迹）。
-- 注意：迁移执行器按分号逐条执行且会剥离 -- 注释行，语句内勿写分号。
-- ============================================================

CREATE TABLE IF NOT EXISTS user_invoice_title (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,
    title_type INT NOT NULL DEFAULT 1,
    title_name VARCHAR(200) NOT NULL DEFAULT '',
    tax_no VARCHAR(32) NOT NULL DEFAULT '',
    company_address VARCHAR(300) NOT NULL DEFAULT '',
    company_phone VARCHAR(32) NOT NULL DEFAULT '',
    bank_name VARCHAR(200) NOT NULL DEFAULT '',
    bank_account VARCHAR(64) NOT NULL DEFAULT '',
    is_default INT NOT NULL DEFAULT 0,
    is_del INT NOT NULL DEFAULT 0,
    add_time INT NOT NULL DEFAULT 0,
    update_time INT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_user_invoice_title_user ON user_invoice_title (user_id, is_del);

CREATE UNIQUE INDEX IF NOT EXISTS uq_user_invoice_title_default ON user_invoice_title (user_id) WHERE is_default = 1 AND is_del = 0;
