-- 采购链「结算」环节：应付单 + 付款登记台账（我方新增）。
-- 设计：~/workspace/vendor-settlement/REPORT.md。
-- 背景：现行采购链（与原版一致）止于对账通过（purchase_reconciliation
-- status=2），无应付/付款单据（演练报告 D13）；用户 2026-11-21 22:48
-- 拍板在对账后新增结算环——只做登记台账，不接真实支付通道、不动钱。
-- 口径：应付与对账单 1:1（UNIQUE reconciliation_id），对账通过时由后端
-- 同步生成（存量已通过对账单由应付列表回填，同一 INSERT 幂等）；
-- 付款登记支持分次付款；应付 status 由已付汇总推导（1 待付款 /
-- 2 部分付款 / 3 已结清），任何接口都不接受外部传入 status。
-- 幂等：CREATE TABLE IF NOT EXISTS / CREATE INDEX IF NOT EXISTS，可重复执行。
-- 生产 auto_migrate=false，部署时先执行本 SQL 再发后端（新二进制读写
-- 两张新表；旧二进制不读新表，前后兼容）。
-- 编号说明：037 已被供应商缺陷批占用（purchase_order_item partial
-- 唯一索引），本迁移取 038；若主聊合并时重排，改文件名即可
-- （迁移执行器只认文件名，代码无引用，头注与 CHANGELOG 措辞同步改）。

BEGIN;

-- 1) 应付单：一行 = 一张已通过对账单的应付义务。
--    payable_amount 生成时快照对账单 total_amount（= 入库额 − 退货额）；
--    paid_amount 为有效付款登记汇总的冗余列，只由登记/作废付款的
--    同事务重算维护；status 与 paid_amount 同步推导落列（见服务层
--    derive_payable_status），列表按 status 过滤即走此列。
CREATE TABLE IF NOT EXISTS purchase_payable (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payable_sn        varchar(64)   NOT NULL DEFAULT '',   -- PS + 秒级时间戳 + 4 位随机（与对账单 PC 同风格）
    reconciliation_id bigint        NOT NULL DEFAULT 0,    -- 来源对账单（1:1）
    reconciliation_sn varchar(64)   NOT NULL DEFAULT '',   -- 来源对账单号快照
    shop_id           integer       NOT NULL DEFAULT 0,    -- 采购组织（随对账单）
    vendor_id         integer       NOT NULL DEFAULT 0,    -- 供应商
    supplier_snapshot text          NOT NULL DEFAULT '',   -- 供应商快照 JSON（随对账单复制）
    payable_amount    numeric(15,2) NOT NULL DEFAULT 0,    -- 应付金额（对账总额快照）
    paid_amount       numeric(15,2) NOT NULL DEFAULT 0,    -- 已付金额（有效登记汇总，事务内维护）
    status            integer       NOT NULL DEFAULT 1,    -- 推导值：1 待付款 / 2 部分付款 / 3 已结清，禁止手工改
    remark            varchar(500)  NOT NULL DEFAULT '',
    create_time       bigint        NOT NULL DEFAULT 0,
    create_by_id      bigint        NOT NULL DEFAULT 0,
    create_by_name    varchar(255)  NOT NULL DEFAULT '',
    update_time       bigint        NOT NULL DEFAULT 0,
    update_by_id      bigint        NOT NULL DEFAULT 0,
    update_by_name    varchar(255)  NOT NULL DEFAULT '',
    is_del            integer       NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_purchase_payable_reconciliation
    ON purchase_payable (reconciliation_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_purchase_payable_sn
    ON purchase_payable (payable_sn) WHERE payable_sn <> '';
CREATE INDEX IF NOT EXISTS idx_purchase_payable_vendor
    ON purchase_payable (vendor_id, id);
CREATE INDEX IF NOT EXISTS idx_purchase_payable_shop_status
    ON purchase_payable (shop_id, status, id);

-- 2) 付款登记：一行 = 一次付款登记（分次付款多行）。
--    只记台账：金额/日期/方式/流水号/凭证备注；作废走 is_del 软删，
--    作废后同事务按有效行汇总重算应付 paid_amount 与 status。
--    pay_method 取值：bank 银行转账 / wechat 微信 / alipay 支付宝 /
--    cash 现金 / other 其他（前端下拉，后端只校验非空与长度）。
CREATE TABLE IF NOT EXISTS purchase_payment (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payable_id     bigint        NOT NULL DEFAULT 0,    -- 所属应付单
    amount         numeric(15,2) NOT NULL DEFAULT 0,    -- 本次付款金额（元，>0）
    pay_date       bigint        NOT NULL DEFAULT 0,    -- 付款日期（epoch 秒，按日登记）
    pay_method     varchar(32)   NOT NULL DEFAULT '',   -- 付款方式代码（见上）
    serial_no      varchar(128)  NOT NULL DEFAULT '',   -- 流水号 / 凭证号
    voucher_remark text          NOT NULL DEFAULT '',   -- 凭证备注
    remark         varchar(500)  NOT NULL DEFAULT '',
    create_time    bigint        NOT NULL DEFAULT 0,
    create_by_id   bigint        NOT NULL DEFAULT 0,
    create_by_name varchar(255)  NOT NULL DEFAULT '',
    update_time    bigint        NOT NULL DEFAULT 0,
    is_del         integer       NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_purchase_payment_payable
    ON purchase_payment (payable_id, id) WHERE is_del = 0;

COMMIT;
