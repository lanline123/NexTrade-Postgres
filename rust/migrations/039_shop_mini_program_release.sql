--
-- 内容：
-- shop_mini_program_version：每个授权小程序一行的版本状态机快照。
--   - stage（本地阶段）：0 未上传 / 1 已上传待提审 / 2 审核中 /
--     3 审核通过待发布 / 4 审核被拒 / 5 已发布。由 commit / submit_audit /
--     audit 同步 / release 动作推导，不许手工改。
--   - audit_status 直接存微信口径：-1 未提审 / 0 审核成功 / 1 审核被拒绝 /
--     2 审核中 / 3 已撤回 / 4 审核延后（官方 get_latest_auditstatus 口径）。
--   - audit_id / template_id / app_version 均可超 i32，统一 bigint。
--   - ext_json 落库留档：每次代提交代码实际下发的 ext 配置（按店生成，
--     含 shopId），便于复现与排障。
-- shop_mini_program_release_log：发布动作流水（只追加）：commit /
--   submit_audit / audit_sync / release / withdraw_audit / revert 六类动作
--   成功与失败都落行（失败带微信 errcode 文案），operator_type 区分平台
--   代操作（platform）与商家自助发起（merchant）。
--
-- 类型口径（本仓现行）：无 SMALLINT；id/标志 INT；时间 INT epoch 秒。

BEGIN;

CREATE TABLE IF NOT EXISTS shop_mini_program_version (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    authorizer_id       integer      NOT NULL,
    shop_id             integer      NOT NULL,
    authorizer_app_id   varchar(64)  NOT NULL DEFAULT '',
    template_id         bigint       NOT NULL DEFAULT 0,
    user_version        varchar(64)  NOT NULL DEFAULT '',
    user_desc           varchar(255) NOT NULL DEFAULT '',
    ext_json            text         NOT NULL DEFAULT '',
    audit_id            bigint       NOT NULL DEFAULT 0,
    audit_status        integer      NOT NULL DEFAULT -1,
    audit_reason        text         NOT NULL DEFAULT '',
    audit_screenshot    text         NOT NULL DEFAULT '',
    audit_user_version  varchar(64)  NOT NULL DEFAULT '',
    submit_audit_time   integer      NOT NULL DEFAULT 0,
    online_user_version varchar(64)  NOT NULL DEFAULT '',
    stage               integer      NOT NULL DEFAULT 0,
    add_time            integer      NOT NULL DEFAULT 0,
    update_time         integer      NOT NULL DEFAULT 0,
    is_del              integer      NOT NULL DEFAULT 0
);

-- 一个授权小程序至多一行版本状态
CREATE UNIQUE INDEX IF NOT EXISTS uq_shop_mini_version_app
    ON shop_mini_program_version (authorizer_app_id) WHERE is_del = 0;

CREATE TABLE IF NOT EXISTS shop_mini_program_release_log (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    authorizer_id     integer     NOT NULL DEFAULT 0,
    shop_id           integer     NOT NULL DEFAULT 0,
    authorizer_app_id varchar(64) NOT NULL DEFAULT '',
    action            varchar(32) NOT NULL DEFAULT '',
    detail            text        NOT NULL DEFAULT '',
    success           integer     NOT NULL DEFAULT 0,
    err_msg           text        NOT NULL DEFAULT '',
    operator_type     varchar(16) NOT NULL DEFAULT '',
    operator_shop_id  integer     NOT NULL DEFAULT 0,
    add_time          integer     NOT NULL DEFAULT 0,
    is_del            integer     NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_shop_mini_release_log_authorizer
    ON shop_mini_program_release_log (authorizer_id, id DESC) WHERE is_del = 0;

COMMIT;
