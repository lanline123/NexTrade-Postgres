CREATE TABLE IF NOT EXISTS shop_auto_comment_setting (
    shop_id INT PRIMARY KEY,
    enabled INT NOT NULL DEFAULT 0,
    days INT NOT NULL DEFAULT 7,
    contents TEXT NOT NULL DEFAULT '',
    update_time INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS order_auto_comment (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INT NOT NULL UNIQUE,
    shop_id INT NOT NULL DEFAULT 0,
    user_id INT NOT NULL DEFAULT 0,
    received_time INT NOT NULL DEFAULT 0,
    days INT NOT NULL DEFAULT 0,
    due_time INT NOT NULL DEFAULT 0,
    content TEXT NOT NULL DEFAULT '',
    status INT NOT NULL DEFAULT 0,
    generated_time INT NOT NULL DEFAULT 0,
    add_time INT NOT NULL DEFAULT 0,
    update_time INT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_order_auto_comment_due ON order_auto_comment (status, due_time);
