-- 内容：
-- shop_mini_program_authorizer：第三方平台授权关系（一授权方一行）。
--   - 与模式① shop_mini_program（商家自填 appid+secret 直连）分开落表：模式②
--     没有 AppSecret，凭据是微信下发的 authorizer_refresh_token —— 按 AI 渠道
--     密钥库口径加密存储（AES-256-GCM，主密钥为服务器环境变量
--     NEXTTRADE_AI_MASTER_KEY），库内只存密文 + nonce + 掩码，明文不落库。
--     refresh token 丢失 = 商家必须重新授权，属最高等级凭据。
--   - status：1 授权中 / 0 已撤销（微信 unauthorized 事件或授权失效）/
--     2 已解绑（后台本地解除绑定；微信侧授权关系以商家在 mp 后台的操作为准，
--     本地解绑后该 appid 立即按未登记拒绝，与模式①解绑同口径）。
--   - 唯一口径：authorizer_app_id 全局唯一一行（is_del=0）；同一店铺同时
--     至多一条 status=1 的授权（部分唯一索引兜底）。同一 appid 不得同时存在
--     模式①启用绑定与模式②授权（服务层在授权完成/直连绑定两处互斥校验）。
--
-- 类型口径（本仓现行）：无 SMALLINT；id/标志 INT；时间 INT epoch 秒。

BEGIN;

CREATE TABLE IF NOT EXISTS shop_mini_program_authorizer (
    id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id              integer NOT NULL,
    authorizer_app_id    varchar(64)  NOT NULL DEFAULT '',
    refresh_token_cipher text         NOT NULL DEFAULT '',
    refresh_token_nonce  varchar(64)  NOT NULL DEFAULT '',
    refresh_token_mask   varchar(32)  NOT NULL DEFAULT '',
    nick_name            varchar(128) NOT NULL DEFAULT '',
    head_img             varchar(512) NOT NULL DEFAULT '',
    user_name            varchar(128) NOT NULL DEFAULT '',
    principal_name       varchar(255) NOT NULL DEFAULT '',
    func_info            text         NOT NULL DEFAULT '',
    status               integer      NOT NULL DEFAULT 1,
    authorized_at        integer      NOT NULL DEFAULT 0,
    last_refresh_at      integer      NOT NULL DEFAULT 0,
    add_time             integer      NOT NULL DEFAULT 0,
    update_time          integer      NOT NULL DEFAULT 0,
    is_del               integer      NOT NULL DEFAULT 0
);

-- 授权方 appid 全局唯一（一 appid 只能授权给一家店）
CREATE UNIQUE INDEX IF NOT EXISTS uq_shop_mini_authorizer_app
    ON shop_mini_program_authorizer (authorizer_app_id) WHERE is_del = 0;

-- 一店同时至多一条生效授权（模式② MVP 口径，与模式①一店一绑定对齐）
CREATE UNIQUE INDEX IF NOT EXISTS uq_shop_mini_authorizer_shop_active
    ON shop_mini_program_authorizer (shop_id) WHERE is_del = 0 AND status = 1;

COMMIT;
