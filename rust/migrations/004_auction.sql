-- 设计见 ~/workspace/auction-design/proposal.md 第 8 节。
-- 时间戳为秒级 INT（与 seckill / order 等既有表一致），金额 NUMERIC(12,2)。
-- 注意：迁移执行器按分号逐条执行且会剥离 -- 注释行，语句内勿写分号。
-- ============================================================

CREATE TABLE IF NOT EXISTS auction_session (
    session_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_name VARCHAR(120) NOT NULL DEFAULT '',
    cover_pic VARCHAR(500) NOT NULL DEFAULT '',
    start_time INT NOT NULL DEFAULT 0,
    end_time INT NOT NULL DEFAULT 0,
    sort INT NOT NULL DEFAULT 0,
    status INT NOT NULL DEFAULT 1,
    add_time INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS auction_item (
    item_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id INT,
    product_id INT NOT NULL,
    sku_id INT NOT NULL DEFAULT 0,
    shop_id INT NOT NULL DEFAULT 0,
    title VARCHAR(255) NOT NULL DEFAULT '',
    start_price NUMERIC(12,2) NOT NULL DEFAULT 0,
    reserve_price NUMERIC(12,2),
    buyout_price NUMERIC(12,2),
    deposit_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    start_time INT NOT NULL DEFAULT 0,
    end_time INT NOT NULL DEFAULT 0,
    real_end_time INT NOT NULL DEFAULT 0,
    extend_count INT NOT NULL DEFAULT 0,
    status INT NOT NULL DEFAULT 0,
    current_price NUMERIC(12,2),
    current_bid_id INT,
    bid_count INT NOT NULL DEFAULT 0,
    winner_user_id INT,
    final_price NUMERIC(12,2),
    order_id INT,
    proxy_max_price NUMERIC(12,2),
    create_admin_id INT NOT NULL DEFAULT 0,
    add_time INT NOT NULL DEFAULT 0,
    update_time INT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_auction_item_status_end ON auction_item (status, real_end_time);

CREATE INDEX IF NOT EXISTS idx_auction_item_product_status ON auction_item (product_id, status);

CREATE INDEX IF NOT EXISTS idx_auction_item_session_status ON auction_item (session_id, status);

CREATE TABLE IF NOT EXISTS auction_bid (
    bid_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id INT NOT NULL,
    user_id INT NOT NULL,
    bid_price NUMERIC(12,2) NOT NULL DEFAULT 0,
    is_buyout INT NOT NULL DEFAULT 0,
    is_proxy INT NOT NULL DEFAULT 0,
    status INT NOT NULL DEFAULT 1,
    ip VARCHAR(64) NOT NULL DEFAULT '',
    user_agent VARCHAR(500) NOT NULL DEFAULT '',
    device_fp VARCHAR(128) NOT NULL DEFAULT '',
    add_time INT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_auction_bid_item_price ON auction_bid (item_id, bid_price DESC);

CREATE INDEX IF NOT EXISTS idx_auction_bid_item_user ON auction_bid (item_id, user_id);

CREATE INDEX IF NOT EXISTS idx_auction_bid_user_time ON auction_bid (user_id, add_time);

CREATE TABLE IF NOT EXISTS auction_deposit (
    deposit_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id INT NOT NULL,
    user_id INT NOT NULL,
    amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    status INT NOT NULL DEFAULT 1,
    balance_log_id INT,
    order_id INT,
    penalty_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    add_time INT NOT NULL DEFAULT 0,
    handle_time INT NOT NULL DEFAULT 0,
    remark VARCHAR(255) NOT NULL DEFAULT ''
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_auction_deposit_item_user ON auction_deposit (item_id, user_id);

CREATE INDEX IF NOT EXISTS idx_auction_deposit_user ON auction_deposit (user_id, status);

CREATE TABLE IF NOT EXISTS auction_breach (
    breach_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,
    item_id INT NOT NULL,
    order_id INT NOT NULL DEFAULT 0,
    deposit_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    penalty_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    breach_time INT NOT NULL DEFAULT 0,
    waived INT NOT NULL DEFAULT 0,
    waive_reason VARCHAR(500) NOT NULL DEFAULT '',
    operator_id INT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_auction_breach_user_time ON auction_breach (user_id, breach_time);

CREATE TABLE IF NOT EXISTS auction_ban (
    ban_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,
    ban_type INT NOT NULL DEFAULT 1,
    start_time INT NOT NULL DEFAULT 0,
    end_time INT NOT NULL DEFAULT 0,
    reason VARCHAR(255) NOT NULL DEFAULT '',
    status INT NOT NULL DEFAULT 1,
    operator_id INT NOT NULL DEFAULT 0,
    add_time INT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_auction_ban_user_status ON auction_ban (user_id, status);

CREATE TABLE IF NOT EXISTS auction_remind (
    remind_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id INT NOT NULL,
    user_id INT NOT NULL,
    notified INT NOT NULL DEFAULT 0,
    add_time INT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_auction_remind_item_user ON auction_remind (item_id, user_id);
