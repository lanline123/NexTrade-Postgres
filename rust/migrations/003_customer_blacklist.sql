CREATE TABLE IF NOT EXISTS user_blacklist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,
    owner_type SMALLINT NOT NULL,
    owner_shop_id INT NOT NULL DEFAULT 0,
    apply_mode SMALLINT NOT NULL DEFAULT 0,
    reason VARCHAR(500) NOT NULL DEFAULT '',
    source SMALLINT NOT NULL DEFAULT 0,
    status SMALLINT NOT NULL DEFAULT 1,
    create_admin_id INT NOT NULL DEFAULT 0,
    create_admin_name VARCHAR(100) NOT NULL DEFAULT '',
    create_admin_type VARCHAR(32) NOT NULL DEFAULT '',
    create_time BIGINT NOT NULL,
    update_time BIGINT NOT NULL,
    remove_admin_id INT NOT NULL DEFAULT 0,
    remove_admin_name VARCHAR(100) NOT NULL DEFAULT '',
    remove_time BIGINT NOT NULL DEFAULT 0,
    remove_reason VARCHAR(500) NOT NULL DEFAULT ''
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_user_blacklist_active ON user_blacklist (user_id, owner_type, owner_shop_id) WHERE status = 1;

CREATE INDEX IF NOT EXISTS idx_user_blacklist_user ON user_blacklist (user_id, status);

CREATE INDEX IF NOT EXISTS idx_user_blacklist_owner ON user_blacklist (owner_type, owner_shop_id, status, create_time DESC);

CREATE TABLE IF NOT EXISTS user_blacklist_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blacklist_id BIGINT NOT NULL,
    product_code VARCHAR(32) NOT NULL,
    behavior_code VARCHAR(32) NOT NULL,
    create_time BIGINT NOT NULL,
    UNIQUE (blacklist_id, product_code, behavior_code),
    CONSTRAINT ck_ubl_rule_combo CHECK (
        (product_code = 'mall' AND behavior_code IN ('place_order', 'product_comment'))
        OR (product_code = 'distribution' AND behavior_code IN ('become_salesman', 'commission_grant'))
        OR (product_code = 'buyer_show' AND behavior_code IN ('buyer_show_publish', 'buyer_show_comment'))
    )
);

CREATE INDEX IF NOT EXISTS idx_ubl_rule_lookup ON user_blacklist_rule (product_code, behavior_code, blacklist_id);

CREATE TABLE IF NOT EXISTS user_blacklist_scope_shop (
    blacklist_id BIGINT NOT NULL,
    shop_id INT NOT NULL,
    PRIMARY KEY (blacklist_id, shop_id)
);

CREATE TABLE IF NOT EXISTS user_blacklist_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blacklist_id BIGINT NOT NULL DEFAULT 0,
    user_id INT NOT NULL DEFAULT 0,
    op_type SMALLINT NOT NULL,
    op_content VARCHAR(1000) NOT NULL DEFAULT '',
    rules_snapshot JSONB NOT NULL DEFAULT '[]',
    scope_snapshot JSONB NOT NULL DEFAULT '{}',
    operator_id INT NOT NULL DEFAULT 0,
    operator_name VARCHAR(100) NOT NULL DEFAULT '',
    operator_type VARCHAR(32) NOT NULL DEFAULT '',
    operator_shop_id INT NOT NULL DEFAULT 0,
    ip VARCHAR(64) NOT NULL DEFAULT '',
    create_time BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_ubl_log_user ON user_blacklist_log (user_id, create_time DESC);

CREATE INDEX IF NOT EXISTS idx_ubl_log_entry ON user_blacklist_log (blacklist_id, create_time DESC);

