-- 幂等：ADD COLUMN IF NOT EXISTS / CREATE TABLE IF NOT EXISTS，可重复执行。
-- 生产 auto_migrate=false，部署时先执行本 SQL 再发后端（新二进制会读写
-- shop_label_rule / shop_label_rule_log 两表与 shop_label_rel 的新列；
-- 旧二进制不读新列，前后兼容）。
-- 编号说明：仓库编号迁移现有最大 027（热更新线占用），本迁移顺延 028。
-- 若主聊合并时重排编号，改文件名即可（迁移执行器只认文件名，代码无引用）。
BEGIN;

-- 1) 分配关系补来源列：区分手动打标与自动授标，冲突策略的根基。
--    source：0 = 平台手动打标（一期整店替换只动这类行）；
--            1 = 自动规则授标（重算只动本规则的这类行）。
--    rule_id：source = 1 时授标规则 id，手动行为 0。
--    add_time：关系建立时间（epoch 秒，一期存量行回填 0）。
ALTER TABLE shop_label_rel ADD COLUMN IF NOT EXISTS source   integer NOT NULL DEFAULT 0;
ALTER TABLE shop_label_rel ADD COLUMN IF NOT EXISTS rule_id  integer NOT NULL DEFAULT 0;
ALTER TABLE shop_label_rel ADD COLUMN IF NOT EXISTS add_time integer NOT NULL DEFAULT 0;

CREATE INDEX IF NOT EXISTS idx_shop_label_rel_rule ON shop_label_rel (rule_id) WHERE source = 1;

-- 2) 自动授标规则：一行 = 一个榜单口径（指标 + 窗口 + 前 N + 门槛）→ 一个标签。
--    metric：sales_amount 成交额 / sales_orders 成交单量 / rating 评分 /
--            collectors 收藏人数（存量口径，不吃窗口，见报告第三节）。
--    min_value：入榜门槛（成交额=元 / 单量=单 / 评分=星 / 收藏=人）。
--    min_samples：样本下限防小样本霸榜（成交额→订单数 / 评分→评价数；
--            单量与收藏的样本即指标本身，服务层忽略此项）。
CREATE TABLE IF NOT EXISTS shop_label_rule (
    rule_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_name        varchar(50)   NOT NULL DEFAULT '',
    label_id         integer       NOT NULL DEFAULT 0,
    metric           varchar(20)   NOT NULL DEFAULT 'sales_amount',
    window_days      integer       NOT NULL DEFAULT 30,
    rank_top         integer       NOT NULL DEFAULT 10,
    min_value        numeric(14,2) NOT NULL DEFAULT 0,
    min_samples      integer       NOT NULL DEFAULT 0,
    status           integer       NOT NULL DEFAULT 1,
    last_run_time    integer       NOT NULL DEFAULT 0,
    last_award_count integer       NOT NULL DEFAULT 0,
    last_remove_count integer      NOT NULL DEFAULT 0,
    add_time         integer       NOT NULL DEFAULT 0,
    update_time      integer       NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_shop_label_rule_label ON shop_label_rule (label_id);

-- 3) 重算流水：每轮一行，留上榜名单快照供运营追溯与验收核对。
--    winners：JSON 数组 [{"shopId":1,"value":"123.45"}, ...]，按名次序。
CREATE TABLE IF NOT EXISTS shop_label_rule_log (
    log_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id      integer      NOT NULL DEFAULT 0,
    run_time     integer      NOT NULL DEFAULT 0,
    trigger_type varchar(10)  NOT NULL DEFAULT 'schedule',
    awarded      integer      NOT NULL DEFAULT 0,
    removed      integer      NOT NULL DEFAULT 0,
    winners      text         NOT NULL DEFAULT '[]'
);

CREATE INDEX IF NOT EXISTS idx_shop_label_rule_log_rule ON shop_label_rule_log (rule_id, log_id DESC);

COMMIT;
