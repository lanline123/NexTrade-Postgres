--
-- 类型口径（本仓现行）：无 SMALLINT；id/标志 INT；时间 INT epoch 秒。

BEGIN;

CREATE TABLE IF NOT EXISTS shop_label (
    label_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label_name varchar(50) NOT NULL DEFAULT '',
    color      varchar(20) NOT NULL DEFAULT '',
    sort_order integer NOT NULL DEFAULT 0,
    status     integer NOT NULL DEFAULT 1,
    add_time   integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS shop_label_rel (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id  integer NOT NULL,
    label_id integer NOT NULL,
    CONSTRAINT uq_shop_label_rel UNIQUE (shop_id, label_id)
);

CREATE INDEX IF NOT EXISTS idx_shop_label_rel_shop ON shop_label_rel (shop_id);
CREATE INDEX IF NOT EXISTS idx_shop_label_rel_label ON shop_label_rel (label_id);

