-- 店铺会员（shop_member）建表与唯一索引（幂等，论坛帖 527763883588791564，用户 2026-11-21 拍板「可以做」）。
--
-- 背景：
-- - 本表对应原版 tigshop v5.8.61 `shop_member`（实体 ShopMember，10 列），
--   我方后端（core 实体/模型、infrastructure 仓储、services 服务、admin 路由）
--   此前已全量移植且实体由基底 schema 生成，仓库内一直没有独立建表迁移。
-- - 2026-11-21 补齐支付记账 record_on_paid 后，部署轮须先保证现网存在
--   该表与 (shop_id, user_id) 唯一约束（记账的「插入→冲突回退累加」依赖它）。
-- - 本迁移只做两件事：表不存在则按实体口径建表；唯一索引不存在则补建。
--   表已存在时不改动存量结构与数据（部署前应先探现网表是否存在，见报告）。
--
-- 口径：
-- - id BIGINT 自增主键；user_id / shop_id INTEGER；order_count INTEGER；
--   order_amount NUMERIC(10,2)；join_time / last_consume_time / create_time /
--   update_time BIGINT（Unix 秒，可空与实体 Option 对齐）；is_del INTEGER 软删。
-- - 唯一索引只建索引不加部分条件：与原版 (shopId, userId) 唯一口径一致；
--   软删行同样占位（与 bindMember 的 count 校验口径一致，软删行存在时
--   添加/记账插入都会冲突回退，不产生第二行）。

BEGIN;

CREATE TABLE IF NOT EXISTS shop_member (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER NOT NULL,
    shop_id           INTEGER NOT NULL,
    order_count       INTEGER NOT NULL DEFAULT 0,
    order_amount      NUMERIC(10, 2) NOT NULL DEFAULT 0,
    join_time         BIGINT,
    last_consume_time BIGINT,
    create_time       BIGINT,
    update_time       BIGINT,
    is_del            INTEGER NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_shop_member_shop_user
    ON shop_member (shop_id, user_id);

COMMENT ON TABLE shop_member IS '店铺会员沉淀表：买家在某店铺的绑定关系与累计消费统计（支付成功自动记账 + 商家添加/导入绑定）';

COMMIT;
