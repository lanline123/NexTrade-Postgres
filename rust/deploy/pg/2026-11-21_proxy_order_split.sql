-- ⚠️ 本文件由代客跨店实施线备好，**未执行**。部署含本功能代码的二进制前
-- 必须先跑本迁移（迁移先于二进制）：新代码在跨店代客单提交后会写
-- proxy_order_ext 表、结算链会读该表，未迁移的库上跨店提交与结算会失败
-- （同店单与其它链路不读该表，不受影响）。
--
-- 内容：
-- proxy_order_ext：代客跨店单的履约归属与三方分成记录（一订单一行）。
--   proxy_shop_id   下单店 = 订单商品所属店铺（现行 order.shop_id，代下单方）
--   fulfill_shop_id 履约门店（下单时按买家地址就近匹配选定，同体系门店）
--   platform_rate / proxy_rate / fulfill_rate：下单时的比例快照（%），
--     平台在订单设置中自定义、三者合计 <= 100 由保存链强校验；
--     结算按快照执行，改比例只影响新单。
--   split_base / platform_amount / proxy_amount / fulfill_amount：
--     结算时回填（分成基数与三方金额；平台份不入任何店铺账户，代收池留存）。
--   split_status：0 待分成 / 1 已分成 / 2 已跳过（线上二级户分账渠道订单
--     在支付侧已分账，不叠加三方分成）。
--
-- 类型口径（本仓现行）：无 SMALLINT；id/标志 INT；金额 NUMERIC；时间 INT epoch 秒。

BEGIN;

CREATE TABLE IF NOT EXISTS proxy_order_ext (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        integer NOT NULL,
    proxy_shop_id   integer NOT NULL DEFAULT 0,
    fulfill_shop_id integer NOT NULL DEFAULT 0,
    platform_rate   numeric(6,2) NOT NULL DEFAULT 0,
    proxy_rate      numeric(6,2) NOT NULL DEFAULT 0,
    fulfill_rate    numeric(6,2) NOT NULL DEFAULT 0,
    split_base      numeric(14,2),
    platform_amount numeric(14,2),
    proxy_amount    numeric(14,2),
    fulfill_amount  numeric(14,2),
    split_status    integer NOT NULL DEFAULT 0,
    add_time        integer NOT NULL DEFAULT 0,
    settle_time     integer
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_proxy_order_ext_order
    ON proxy_order_ext (order_id);

COMMIT;
