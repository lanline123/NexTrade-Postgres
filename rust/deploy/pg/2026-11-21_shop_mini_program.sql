-- user_authorize.app_id 列，未迁移的库上绑定管理、小程序登录与店铺作用域
-- 解析都会因表/列不存在而失败（部署顺序约束）。
--
-- 内容：
-- 1) shop_mini_program：店铺 ↔ 自有小程序绑定（一店一 appid、appid 全局唯一）。
--    AppSecret 按 AI 渠道密钥库口径加密存储（AES-256-GCM，主密钥为服务器环境
--    变量 NEXTTRADE_AI_MASTER_KEY），库内只存密文 + nonce + 掩码，明文不落库。
--    status：1 启用 / 0 停用（停用或解绑后该 appid 的请求立即按未登记拒绝）。
-- 2) user_authorize.app_id：小程序授权（authorize_type=2）的 appid 维度。
--    平台小程序与存量行一律 ''（空串哨兵）；店铺小程序写其 appid 本身。
--    同一买家在不同小程序下 openid 不同，必须按 (openid, type, app_id) 区分，
--    会员归一锚点为手机号（复用 bindMobile 合并链），不用 unionid 跨主体认人。
--
-- 类型口径（本仓现行）：无 SMALLINT；id/标志 INT；时间 INT epoch 秒。

BEGIN;

CREATE TABLE IF NOT EXISTS shop_mini_program (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id           integer NOT NULL,
    app_id            varchar(64) NOT NULL DEFAULT '',
    app_secret_cipher text    NOT NULL DEFAULT '',
    app_secret_nonce  varchar(64) NOT NULL DEFAULT '',
    secret_mask       varchar(32) NOT NULL DEFAULT '',
    status            integer NOT NULL DEFAULT 1,
    verified_at       integer NOT NULL DEFAULT 0,
    remark            varchar(255) NOT NULL DEFAULT '',
    add_time          integer NOT NULL DEFAULT 0,
    update_time       integer NOT NULL DEFAULT 0,
    is_del            integer NOT NULL DEFAULT 0
);

-- appid 全局唯一（一 appid 只能绑一店）、一店只绑一个小程序（MVP 口径）
CREATE UNIQUE INDEX IF NOT EXISTS uq_shop_mini_program_app
    ON shop_mini_program (app_id) WHERE is_del = 0;
CREATE UNIQUE INDEX IF NOT EXISTS uq_shop_mini_program_shop
    ON shop_mini_program (shop_id) WHERE is_del = 0;

ALTER TABLE user_authorize ADD COLUMN IF NOT EXISTS app_id varchar(64) NOT NULL DEFAULT '';

CREATE INDEX IF NOT EXISTS idx_user_authorize_open_app
    ON user_authorize (open_id, authorize_type, app_id);

COMMIT;
