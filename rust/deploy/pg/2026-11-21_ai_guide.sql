--
-- 内容：
-- 1) ai_usage 扩维：user_id（买家维度）/ scene（admin|guide）。存量行默认
--    admin/0，运营助手的既有列表查询不读新列、零改动兼容。
-- 2) 导购独立会话表 ai_guide_conversation / ai_guide_message（不混 admin 的
--    ai_conversation/ai_message 语义：主体是买家、平台维度、全只读工具）。
-- 3) 导购设置走 config.biz_code = 'aiGuideSettings'（JSON），无行时代码走
--    内置默认（enabled=true、sessionTokens=60000、userDailyTokens=200000、
--    globalDailyTokens=5000000）；如需改阈值，部署时按注释示例插入一行。
--
-- 类型口径（本仓现行）：无 SMALLINT；id/标志 INT；token/时间戳 BIGINT epoch 秒。

BEGIN;

ALTER TABLE ai_usage ADD COLUMN IF NOT EXISTS user_id integer NOT NULL DEFAULT 0;
ALTER TABLE ai_usage ADD COLUMN IF NOT EXISTS scene varchar(20) NOT NULL DEFAULT 'admin';

CREATE INDEX IF NOT EXISTS idx_ai_usage_scene_user_time
    ON ai_usage (scene, user_id, create_time DESC);

CREATE TABLE IF NOT EXISTS ai_guide_conversation (
    conv_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     integer NOT NULL,
    title       varchar(200) NOT NULL DEFAULT '',
    channel_id  integer NOT NULL DEFAULT 0,
    model_code  varchar(100) NOT NULL DEFAULT '',
    is_del      integer NOT NULL DEFAULT 0,
    create_time bigint NOT NULL DEFAULT 0,
    update_time bigint NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_ai_guide_conv_user
    ON ai_guide_conversation (user_id, is_del, update_time DESC);

CREATE TABLE IF NOT EXISTS ai_guide_message (
    msg_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conv_id           integer NOT NULL,
    role              integer NOT NULL,
    content           text NOT NULL DEFAULT '',
    tool_calls        jsonb,
    tool_name         varchar(100),
    tool_status       integer NOT NULL DEFAULT 0,
    prompt_tokens     integer NOT NULL DEFAULT 0,
    completion_tokens integer NOT NULL DEFAULT 0,
    create_time       bigint NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_ai_guide_msg_conv
    ON ai_guide_message (conv_id, msg_id);

COMMENT ON TABLE ai_guide_conversation IS 'AI 导购会话（买家维度，平台渠道）';
COMMENT ON TABLE ai_guide_message IS 'AI 导购消息：role 1买家/2助手/3工具；tool 行 tool_calls={callId,cards} 供回显渲染商品卡';
COMMENT ON COLUMN ai_usage.user_id IS '买家 user id（scene=guide 时有效；admin 场景恒 0）';
COMMENT ON COLUMN ai_usage.scene IS '场景：admin=运营助手 / guide=买家导购';

-- 导购阈值如需调整：部署时在 config 表加一行 biz_code='aiGuideSettings'，
-- biz_val 为 JSON（列形照既有 config 行补齐）：
--   {"enabled":true,"sessionTokens":60000,"userDailyTokens":200000,"globalDailyTokens":5000000}

COMMIT;
